// Regenerate the model → vendor-icon table and the icon files it points at, from
// LobeHub's own data (MIT). Run when Lobe adds vendors:
//
//   npm pack @lobehub/icons @lobehub/icons-static-svg   (in an empty folder)
//   tar xzf each, into two folders
//   node scripts/gen-model-icons.mjs <icons pkg dir> <icons-static-svg pkg dir>
//
// Reads `es/features/modelConfig.mjs` — the ordered keyword table Lobe's own
// ModelIcon component uses — as text, never by importing it, and copies only
// the SVGs that table refers to into public/model-icons/. Every SVG is checked
// for active content before it is copied.
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, copyFileSync } from 'node:fs';
import path from 'node:path';

const [iconsPkg, svgPkg] = process.argv.slice(2);
if (!iconsPkg || !svgPkg) {
  console.error('usage: node scripts/gen-model-icons.mjs <@lobehub/icons dir> <@lobehub/icons-static-svg dir>');
  process.exit(1);
}

const config = readFileSync(path.join(iconsPkg, 'es/features/modelConfig.mjs'), 'utf8');
const iconsVersion = JSON.parse(readFileSync(path.join(iconsPkg, 'package.json'), 'utf8')).version;
const svgVersion = JSON.parse(readFileSync(path.join(svgPkg, 'package.json'), 'utf8')).version;

// import Icons$12 from "../Aya/index.mjs";
const folderOf = new Map();
for (const m of config.matchAll(/^import (Icons(?:\$\d+)?) from "\.\.\/([A-Za-z0-9]+)\/index\.mjs";$/gm)) {
  folderOf.set(m[1], m[2]);
}

const body = config.slice(config.indexOf('const modelMappings = ['));
const rules = [];
for (const m of body.matchAll(/Icon: (Icons(?:\$\d+)?),\s*keywords: (\[[^\]]*\])/g)) {
  const folder = folderOf.get(m[1]);
  if (!folder) throw new Error(`no import for ${m[1]}`);
  const keywords = JSON.parse(m[2]);
  for (const k of keywords) new RegExp(k, 'i'); // throws on a pattern JS cannot compile
  rules.push({ folder, keywords });
}
if (rules.length < 50) throw new Error(`only ${rules.length} rules parsed — has the file format changed?`);

const ACTIVE = /<script|\son[a-z]+\s*=|href\s*=|<foreignObject|javascript:|<iframe|<image/i;
const outDir = 'public/model-icons';
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const files = new Map(); // icon name → { mono }
const table = [];
for (const { folder, keywords } of rules) {
  const name = folder.toLowerCase();
  if (!files.has(name)) {
    const color = path.join(svgPkg, 'icons', `${name}-color.svg`);
    const mono = path.join(svgPkg, 'icons', `${name}.svg`);
    const src = existsSync(color) ? color : existsSync(mono) ? mono : null;
    if (!src) {
      console.warn(`skip ${folder}: no svg`);
      continue;
    }
    const svg = readFileSync(src, 'utf8');
    if (ACTIVE.test(svg)) throw new Error(`active content in ${src}`);
    copyFileSync(src, path.join(outDir, `${name}.svg`));
    files.set(name, { mono: src === mono });
  }
  // Consecutive rules for one icon (OpenAI's model families) merge into one.
  const last = table[table.length - 1];
  if (last && last.icon === name) last.keywords.push(...keywords);
  else table.push({ icon: name, keywords: [...keywords] });
}

writeFileSync(path.join(outDir, 'LICENSE'), readFileSync(path.join(iconsPkg, 'LICENSE'), 'utf8'));

const mono = [...files].filter(([, f]) => f.mono).map(([n]) => n).sort();
const ts = `// GENERATED by scripts/gen-model-icons.mjs from @lobehub/icons ${iconsVersion}
// and @lobehub/icons-static-svg ${svgVersion} (MIT, LobeHub). Do not edit by hand.

/**
 * Lobe's model → icon table, in Lobe's order: the first rule with a pattern
 * matching the lowercased model id wins. Each icon is a file in
 * public/model-icons/<icon>.svg.
 */
export const MODEL_ICON_RULES: readonly (readonly [icon: string, patterns: readonly string[]])[] = [
${table.map((r) => `  [${JSON.stringify(r.icon)}, ${JSON.stringify(r.keywords)}],`).join('\n')}
];

/** Icons that come in one colour only and should be painted with currentColor. */
export const MONO_MODEL_ICONS: ReadonlySet<string> = new Set(${JSON.stringify(mono)});
`;
writeFileSync('src/core/providers/modelIcons.generated.ts', ts);
console.log(`${table.length} rules, ${files.size} icons (${mono.length} monochrome) → ${outDir}`);
